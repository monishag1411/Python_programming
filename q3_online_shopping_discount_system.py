order_amount = float(input("Enter the order amount: "))
membership = input("Are you a member? (yes/no): ").strip().lower()

if order_amount < 0 or order_amount > 100000:
    print("Invalid order amount.")

elif membership != "yes" and membership != "no":
    print("Invalid membership status. Please enter yes or no.")

else:
    if order_amount >= 5000:
        discount = order_amount * 15 / 100
        eligibility = "Eligible for 15% discount"

    elif order_amount >= 2000 and membership == "yes":
        discount = order_amount * 10 / 100
        eligibility = "Eligible for 10% discount"

    else:
        discount = 0
        eligibility = "Not eligible for discount"

    final_amount = order_amount - discount

    print("Original Order Amount:", order_amount)
    print("Discount Amount:", discount)
    print("Final Payable Amount:", final_amount)
    print("Discount Eligibility:", eligibility)